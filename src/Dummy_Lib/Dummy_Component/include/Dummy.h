  //// PRIVATE /////////////////////////////////    SETTERS & GETTERS    ///////////////////////////////////////////////
  //////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

  //// PRIVATE /////////////////////////////////        OPERATORS        ///////////////////////////////////////////////
  //////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

  //// PRIVATE /////////////////////////////////      CONSTRUCTORS       ///////////////////////////////////////////////
